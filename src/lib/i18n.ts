export const TRANSLATIONS: Record<Language, Dict> = { en, 'zh-CN': zh }

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const template = TRANSLATIONS[language][key] ?? TRANSLATIONS.en[key] ?? key
  if (!vars) return template
  return Object.entries(vars).reduce((str, [k, v]) => str.replace(`{${k}}`, String(v)), template)
}
